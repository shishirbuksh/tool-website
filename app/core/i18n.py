_LOCALE_SET = set(SUPPORTED_LOCALES)


def is_supported_locale(value: str | None) -> bool:
    return bool(value) and value.strip().lower() in _LOCALE_SET


def normalize_locale(value: str | None) -> str:
    return DEFAULT_LOCALE


def split_locale_path(path: str) -> tuple[str, str]:
    """Split '/hi/tool/x' -> ('hi', '/tool/x'); '/tool/x' -> ('en', '/tool/x')."""
    if not path.startswith("/"):
        path = "/" + path
    parts = path.split("/", 2)
    # Detect legacy multi-language prefixes for 301 redirection
    if len(parts) >= 2 and parts[1].lower() in {"hi", "es", "fr", "de"}:
        rest = "/" + parts[2] if len(parts) > 2 else "/"
        return parts[1].lower(), rest
    return DEFAULT_LOCALE, path


def localize_path(path: str, locale: str = "en") -> str:
    """Return canonical path without language prefix."""
    _, bare = split_locale_path(path)
    return bare


def localize_url(site_url: str, path: str, locale: str = "en") -> str:
    return site_url.rstrip("/") + localize_path(path, locale)


def hreflang_links(
    site_url: str, bare_path: str, locales: list[str] | tuple[str, ...] | None = None
) -> list[dict[str, str]]:
    """Only English and x-default links."""
    base = site_url.rstrip("/")
    _, bare = split_locale_path(bare_path)
    return [
        {"hreflang": "en", "href": base + bare},
        {"hreflang": "x-default", "href": base + bare},
    ]


def og_locale_for(locale: str = "en") -> str:
    return "en_US"


def html_lang_for(locale: str = "en") -> str:
    return "en"


